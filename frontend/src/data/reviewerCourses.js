const attachmentMimeTypes = {
  csv: 'text/csv',
  ipynb: 'application/x-ipynb+json',
  pdf: 'application/pdf',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  zip: 'application/zip',
}

const createAttachment = (courseId, fileName) => {
  const extension = fileName.split('.').pop()?.toLowerCase()

  return {
    id: `${courseId}-${fileName}`,
    fileName,
    mimeType: attachmentMimeTypes[extension] || '',
    fileUrl: '',
    sizeBytes: null,
    uploadedBy: '',
    uploadedAt: '',
    lessonId: '',
    description: '',
  }
}

